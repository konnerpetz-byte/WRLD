/**
 * Trip vibes: what a place is good for, to filter and tailor searches. A place can have several.
 * Tagged by hand for every road-trip spot and every flight destination WRLD prices.
 */
export const VIBES = [
  { key: "water", label: "Beaches & lakes" },
  { key: "outdoors", label: "Hiking & outdoors" },
  { key: "historic", label: "Historic towns" },
  { key: "food", label: "Food, wine & breweries" },
  { key: "nightlife", label: "Nightlife & music" },
  { key: "culture", label: "Museums & arts" },
  { key: "quiet", label: "Small town & quiet" },
  { key: "family", label: "Family & theme parks" },
  { key: "snow", label: "Snow & skiing" },
  { key: "city", label: "Big city" },
] as const;
export type Vibe = (typeof VIBES)[number]["key"];
const VALID = new Set<string>(VIBES.map((v) => v.key));

/** "water,outdoors" → ["water", "outdoors"] */
export const parseVibes = (raw: string | undefined): Vibe[] =>
  [...new Set((raw ?? "").split(",").map((s) => s.trim()).filter((s) => VALID.has(s)))] as Vibe[];

type Meta = { season: Season; vibes: Vibe[] };
const m = (season: Season, ...vibes: Vibe[]): Meta => ({ season, vibes });

